## Inflação

Inflação é o aumento geral dos preços ao longo do tempo. Com ela, a mesma quantia compra menos coisas no futuro do que compra hoje. Por isso se diz que dinheiro parado perde poder de compra.

## Juros simples e compostos

Juros são o preço do dinheiro no tempo. Nos juros simples, o cálculo incide só sobre o valor inicial. Nos juros compostos, incide sobre o valor inicial somado aos juros já acumulados: os "juros sobre juros".

Exemplo ilustrativo, com R$ 1.000 a 10% ao ano por 3 anos:

- Juros simples: R$ 100 por ano, chegando a R$ 1.300.
- Juros compostos: R$ 1.100, depois R$ 1.210 e depois R$ 1.331.

## Dois lados da mesma moeda

Os juros compostos podem trabalhar a seu favor em uma aplicação, mas também contra você em uma dívida, como no cartão de crédito ou no cheque especial, onde o valor pode crescer rápido. As taxas do exemplo são fictícias e servem só para ilustrar o cálculo.$t$,
